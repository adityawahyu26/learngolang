// compare dalam bahasa pemrograman Go
package main

import "fmt"

func main() {
	// deklarasi variabel a dan b
	a := 26
	b := 12
	
	fmt.Println("a :", a)
	fmt.Println("b :", b)

	// apa a lebih besar dari b
	fmt.Println("a > b :", a > b)

	// apa a lebih kecil dari b
	fmt.Println("a < b :", a < b)

	// apa a lebih besar sama dengan b
	fmt.Println("a >= b :", a >= b)

	// apa a lebih kecil sama dengan b
	fmt.Println("a <= b :", a <= b)

	// apa a sama dengan b
	fmt.Println("a == b :", a == b)

	// apa a tidak sama dengan b
	fmt.Println("a != b :", a != b)
}