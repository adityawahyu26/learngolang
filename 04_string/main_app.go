package main

import "fmt"

func main() {
	// mennampilkan string
	fmt.Println("adit")
	fmt.Println("aditya")
	fmt.Println("aditya wahyu")
	
	// menampilkan panjang string
	fmt.Println(len("adit"))
	// menampilkan karakter string dengan index tertentu
	// dalam bentuk karaketer ASCII
	fmt.Println("aditya"[0])
	fmt.Println("aditya wahyu"[1])
}